import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

class ArsenalTests(unittest.TestCase):
    def test_all_weapons_have_specs(self):
        weapons = json.loads((ROOT / "data/weapons.json").read_text(encoding="utf-8"))
        data = json.loads((ROOT / "data/attachments.json").read_text(encoding="utf-8"))
        self.assertEqual(len(weapons), 35)
        self.assertEqual({x["id"] for x in weapons}, set(data["specs"]))

    def test_attachment_slots(self):
        data = json.loads((ROOT / "data/attachments.json").read_text(encoding="utf-8"))
        for item in data["items"]:
            for weapon in item["weapons"]:
                self.assertIn(item["type"], data["specs"][weapon]["types"])

    def test_site_loads_expansion(self):
        index = (ROOT / "index.html").read_text(encoding="utf-8")
        self.assertLess(index.index('data/attachments.js'), index.index('data/attachment-expansion.js'))
        self.assertLess(index.index('data/attachment-expansion.js'), index.index('src="app.js"'))
        self.assertIn('mw4:arsenal-ready', (ROOT / "app.js").read_text(encoding="utf-8"))

    def test_snapshot_if_published(self):
        path = ROOT / "data" / "attachments-community.json"
        if not path.exists():
            self.skipTest("Catalog generated by the sync workflow")
        data = json.loads(path.read_text(encoding="utf-8"))
        self.assertEqual(data["meta"]["status"], "community-reported")
        self.assertGreaterEqual(len(data["attachments"]), 500)

if __name__ == "__main__":
    unittest.main()
