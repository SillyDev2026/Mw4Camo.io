'use strict';
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const context={window:{},Date,Set};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','feed-guard.js'),'utf8'),context);
const guard=context.window.MW4_FEED_GUARD;
const record={id:'official-mw4-2026-11-16',date:'2026-11-16',game:'MW4',title:'Test snapshot',source:'https://www.callofduty.com/patchnotes/2026/11/example',sections:[{title:'Weapon changes',points:['A valid note']} ]};
const old=[record],revised=[record,{...record,id:'new-article'}];
const status={lastCheckedAt:'2026-11-16T08:00:00Z',lastSuccessfulAt:'2026-11-16T07:00:00Z',patchCount:2};
assert.equal(guard.patchArchive(revised),true);
assert.equal(guard.status(status,revised),true);
assert.equal(guard.preservesArchive(old,revised),true);
assert.equal(guard.patchArchive([{...record,sections:[{title:'x',points:null}]}]),false);
assert.equal(guard.patchArchive([{...record,sections:[{title:'x',points:[{}]}]}]),false);
assert.equal(guard.patchArchive([{...record,source:'https://attacker.test/notes'}]),false);
assert.equal(guard.patchArchive([record,{...record}]),false,'duplicate id is rejected');
assert.equal(guard.patchArchive([{...record,date:'tomorrow'}]),false);
assert.equal(guard.status({...status,patchCount:6},revised),false);
assert.equal(guard.status({...status,lastCheckedAt:'not-a-date'},revised),false);
assert.equal(guard.status({...status,lastSuccessfulAt:'2027-01-01T00:00:00Z'},revised),false);
assert.equal(guard.preservesArchive(revised,old),false,'truncated source cannot delete known notes');
console.log('Patch snapshot guard passed: structure, sources, timestamps, duplicates, counts, and archive preservation.');
